// Captures a released client's own decoding code for the mixed-version
// compatibility matrix (docs/tactical/359-mixed-version-compatibility-matrix.md).
//
//   node scripts/compat-capture.mjs --release extension-1.1.4 \
//     --commit 5fa018ff589f8058f6ed3910f5cea5fcd06410ab --role client
//
// The release's source is checked out into a temporary git worktree and its
// validation.ts and view-set-reducer.ts are bundled, unmodified, into one
// self-contained module. Nothing in the worktree is committed; the worktree
// is removed afterwards. Run it once per release, outside ordinary CI, and
// commit compat/captures/<release>/.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const webModules = path.join(root, "clients/web/node_modules");

/** Exports the bundle provides; a release lacking one cannot be captured. */
const ENTRY = `export {
  decodeApiHello,
  decodeOpenViewSetResponse,
  decodeUpdateBatch,
} from "./validation";
export { reduceOpenViewSet, reduceUpdateBatch } from "./view-set-reducer";
`;

/** Types for importing the captured decoder from the current test suites. */
const DECLARATIONS = `// Generated by scripts/compat-capture.mjs. Do not edit.
export declare function decodeApiHello(source: string): unknown;
export declare function decodeOpenViewSetResponse(source: string): unknown;
export declare function decodeUpdateBatch(source: string): unknown;
export declare function reduceOpenViewSet(response: unknown): unknown;
export declare function reduceUpdateBatch(state: unknown, batch: unknown): unknown;
`;

function options(argv) {
  const parsed = Object.fromEntries(
    argv.flatMap((value, index) => (value.startsWith("--") ? [[value.slice(2), argv[index + 1]]] : [])),
  );
  if (!/^[a-z]+-[0-9][0-9.]*$/.test(parsed.release ?? "") || !/^[0-9a-f]{40}$/.test(parsed.commit ?? "")) {
    throw new Error("usage: compat-capture.mjs --release <surface-version> --commit <40-hex sha> --role client");
  }
  if (parsed.role !== "client") throw new Error("only --role client is captured so far");
  return parsed;
}

function digest(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function git(args, cwd = root) {
  return execFileSync("git", args, { cwd, encoding: "utf8" }).trim();
}

async function main() {
  const { release, commit, role } = options(process.argv.slice(2));
  const peeled = git(["rev-parse", `${commit}^{commit}`]);
  if (peeled !== commit) throw new Error(`${commit} does not name a commit`);
  const output = path.join(root, "compat/captures", release);
  const worktree = mkdtempSync(path.join(tmpdir(), `compat-${release}-`));
  rmSync(worktree, { recursive: true });
  git(["worktree", "add", "--detach", worktree, commit]);
  try {
    const source = path.join(worktree, "clients/web/src");
    // Bundling only; the release's own sources import nothing from npm.
    symlinkSync(webModules, path.join(worktree, "clients/web/node_modules"), "dir");
    const entry = path.join(source, "compat-capture-entry.ts");
    writeFileSync(entry, ENTRY);
    const { build } = await import(pathToFileURL(path.join(webModules, "rolldown/dist/index.mjs")).href);
    const result = await build({
      input: entry,
      platform: "neutral",
      write: false,
      output: { format: "esm", minify: true, codeSplitting: false },
      logLevel: "warn",
    });
    const chunks = result.output.filter((item) => item.type === "chunk");
    if (chunks.length !== 1) throw new Error(`expected one bundled chunk, got ${chunks.length}`);
    const decoder = `// Captured by scripts/compat-capture.mjs from ${release} at ${commit}. Do not edit.\n${chunks[0].code}`;
    const sources = ["validation.ts", "view-set-reducer.ts", "api/generated/v1.validators.js", "api/generated/v1.schema.json"];
    mkdirSync(output, { recursive: true });
    writeFileSync(path.join(output, "client-decoder.mjs"), decoder);
    writeFileSync(path.join(output, "client-decoder.d.mts"), DECLARATIONS);
    const schema = readFileSync(path.join(source, "api/generated/v1.schema.json"));
    writeFileSync(path.join(output, "v1.schema.json"), schema);
    const provenance = {
      release,
      commit,
      roles: [role],
      capturedWith: {
        node: process.version,
        rolldown: JSON.parse(readFileSync(path.join(webModules, "rolldown/package.json"), "utf8")).version,
      },
      sourceDigests: Object.fromEntries(
        sources.map((file) => [`clients/web/src/${file}`, digest(readFileSync(path.join(source, file)))]),
      ),
      artifactDigests: {
        "client-decoder.mjs": digest(decoder),
        "v1.schema.json": digest(schema),
      },
    };
    writeFileSync(path.join(output, "provenance.json"), `${JSON.stringify(provenance, null, 2)}\n`);
    console.log(`captured ${release} (${commit}) into ${path.relative(root, output)}`);
  } finally {
    git(["worktree", "remove", "--force", worktree]);
  }
}

await main();
