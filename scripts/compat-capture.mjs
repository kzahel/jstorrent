// Captures what a released commit's own source produces, for the
// mixed-version compatibility matrix
// (docs/tactical/359-mixed-version-compatibility-matrix.md).
//
//   source scripts/dev-env.sh
//   node scripts/compat-capture.mjs --commit <40-hex sha> --roles host,client
//
// The commit is checked out into a temporary git worktree. Nothing there is
// committed, and the worktree is removed afterwards. Output goes to
// compat/captures/<commit>/; compat/deliveries.json maps published
// deliveries to captures. Run once per commit, outside ordinary CI.
//
// - client: the release's validation.ts and view-set-reducer.ts, bundled
//   unmodified into one module (client-decoder.mjs).
// - host: the release's own export_types output (schema and traces) and, from
//   a temporary example program, its ApiHello::default() and fresh-profile
//   settings runtime view. Platform-added hello facts are not included.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const webModules = path.join(root, "clients/web/node_modules");

/** Exports the client bundle provides; a release lacking one cannot be captured. */
const CLIENT_ENTRY = `export {
  decodeApiHello,
  decodeOpenViewSetResponse,
  decodeUpdateBatch,
} from "./validation";
export { reduceOpenViewSet, reduceUpdateBatch } from "./view-set-reducer";
`;

/** Types for importing a captured decoder from the current test suites. */
const CLIENT_DECLARATIONS = `// Generated by scripts/compat-capture.mjs. Do not edit.
export declare function decodeApiHello(source: string): unknown;
export declare function decodeOpenViewSetResponse(source: string): unknown;
export declare function decodeUpdateBatch(source: string): unknown;
export declare function reduceOpenViewSet(response: unknown): unknown;
export declare function reduceUpdateBatch(state: unknown, batch: unknown): unknown;
`;

/** Prints the release's own hello and default settings view. */
const HOST_EXAMPLE = `fn main() {
    let output = std::path::PathBuf::from(std::env::args().nth(1).expect("output directory"));
    let hello = serde_json::to_string_pretty(&rstorrent_session::ApiHello::default()).unwrap();
    std::fs::write(output.join("hello.json"), hello + "\\n").unwrap();
    let settings = serde_json::to_string_pretty(
        &rstorrent_session::ClientSettingsRuntimeView::fresh_profile_default(),
    )
    .unwrap();
    std::fs::write(output.join("settings.json"), settings + "\\n").unwrap();
}
`;

function options(argv) {
  const parsed = Object.fromEntries(
    argv.flatMap((value, index) => (value.startsWith("--") ? [[value.slice(2), argv[index + 1]]] : [])),
  );
  const roles = (parsed.roles ?? "").split(",").filter(Boolean);
  if (
    !/^[0-9a-f]{40}$/.test(parsed.commit ?? "") ||
    roles.length === 0 ||
    roles.some((role) => role !== "host" && role !== "client")
  ) {
    throw new Error("usage: compat-capture.mjs --commit <40-hex sha> --roles host,client");
  }
  return { commit: parsed.commit, roles: [...new Set(roles)].sort() };
}

function digest(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function run(command, args, cwd, env = {}) {
  return execFileSync(command, args, {
    cwd,
    encoding: "utf8",
    env: { ...process.env, ...env },
    stdio: ["ignore", "pipe", "inherit"],
  }).trim();
}

async function captureClient(source, output) {
  // Bundling only; the release's own decoding sources import nothing from npm.
  symlinkSync(webModules, path.join(source, "..", "node_modules"), "dir");
  const entry = path.join(source, "compat-capture-entry.ts");
  writeFileSync(entry, CLIENT_ENTRY);
  const { build } = await import(pathToFileURL(path.join(webModules, "rolldown/dist/index.mjs")).href);
  const result = await build({
    input: entry,
    platform: "neutral",
    write: false,
    output: { format: "esm", minify: true, codeSplitting: false },
    logLevel: "warn",
  });
  const chunks = result.output.filter((item) => item.type === "chunk");
  if (chunks.length !== 1) throw new Error(`expected one bundled chunk, got ${chunks.length}`);
  writeFileSync(
    path.join(output, "client-decoder.mjs"),
    `// Captured by scripts/compat-capture.mjs. Do not edit.\n${chunks[0].code}`,
  );
  writeFileSync(path.join(output, "client-decoder.d.mts"), CLIENT_DECLARATIONS);
  return ["validation.ts", "view-set-reducer.ts", "api/generated/v1.validators.js"].map(
    (file) => path.join(source, file),
  );
}

function captureHost(worktree, output) {
  const targetDir = path.join(root, "target/compat-capture");
  const scratch = mkdtempSync(path.join(tmpdir(), "compat-host-"));
  try {
    run(
      "cargo",
      [
        "run", "--locked", "--quiet", "-p", "rstorrent-gateway", "--bin", "export_types", "--",
        path.join(scratch, "v1.ts"),
        path.join(output, "v1.schema.json"),
        path.join(output, "reactive-trace.json"),
        path.join(output, "view-set-trace.json"),
      ],
      worktree,
      { CARGO_TARGET_DIR: targetDir },
    );
    const examples = path.join(worktree, "crates/rstorrent-gateway/examples");
    mkdirSync(examples, { recursive: true });
    writeFileSync(path.join(examples, "compat_capture.rs"), HOST_EXAMPLE);
    run(
      "cargo",
      ["run", "--locked", "--quiet", "-p", "rstorrent-gateway", "--example", "compat_capture", "--", output],
      worktree,
      { CARGO_TARGET_DIR: targetDir },
    );
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
  return [
    "crates/rstorrent-session/src/views/contract.rs",
    "crates/rstorrent-session/src/settings/contract.rs",
  ].map((file) => path.join(worktree, file));
}

async function main() {
  const { commit, roles } = options(process.argv.slice(2));
  if (run("git", ["rev-parse", `${commit}^{commit}`], root) !== commit) {
    throw new Error(`${commit} does not name a commit`);
  }
  const output = path.join(root, "compat/captures", commit);
  rmSync(output, { recursive: true, force: true });
  mkdirSync(output, { recursive: true });
  const worktree = mkdtempSync(path.join(tmpdir(), `compat-${commit.slice(0, 12)}-`));
  rmSync(worktree, { recursive: true });
  run("git", ["worktree", "add", "--detach", worktree, commit], root);
  try {
    const source = path.join(worktree, "clients/web/src");
    const inputs = [];
    if (roles.includes("host")) {
      inputs.push(...captureHost(worktree, output));
    } else {
      writeFileSync(
        path.join(output, "v1.schema.json"),
        readFileSync(path.join(source, "api/generated/v1.schema.json")),
      );
    }
    if (roles.includes("client")) inputs.push(...(await captureClient(source, output)));
    const artifacts = [
      "v1.schema.json",
      "reactive-trace.json",
      "view-set-trace.json",
      "hello.json",
      "settings.json",
      "client-decoder.mjs",
    ].filter((file) => existsSync(path.join(output, file)));
    const provenance = {
      commit,
      roles,
      capturedWith: {
        node: process.version,
        rustc: run("rustc", ["--version"], worktree),
        rolldown: JSON.parse(readFileSync(path.join(webModules, "rolldown/package.json"), "utf8")).version,
      },
      sourceDigests: Object.fromEntries(
        inputs.map((file) => [path.relative(worktree, file), digest(readFileSync(file))]),
      ),
      artifactDigests: Object.fromEntries(
        artifacts.map((file) => [file, digest(readFileSync(path.join(output, file)))]),
      ),
    };
    writeFileSync(path.join(output, "provenance.json"), `${JSON.stringify(provenance, null, 2)}\n`);
    console.log(`captured ${commit} (${roles.join(", ")}) into ${path.relative(root, output)}`);
  } finally {
    run("git", ["worktree", "remove", "--force", worktree], root);
  }
}

await main();
