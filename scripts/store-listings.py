#!/usr/bin/env python3
"""Reviewed production store text, native Chrome catalogs and Play metadata edits."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import sys
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import localization

_spec = importlib.util.spec_from_file_location('android_play', ROOT / 'scripts/android-play.py')
play = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(play)
DIRECTORY = ROOT / 'distribution/store-listings'
FIELDS = {'play_title': 'title', 'play_short': 'shortDescription', 'play_full': 'fullDescription'}
MAX_JSON = 4 * 1024 * 1024


def read(path):
    if Path(path).stat().st_size > MAX_JSON:
        raise ValueError('Store data exceeds 4 MiB')
    return localization.read_json(Path(path))


def write(path, value):
    localization.atomic_write(Path(path), localization.json_text(value))


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(',', ':')).encode()).hexdigest()


def configuration(root=ROOT):
    config = read(root / 'distribution/store-listings/locales.json')
    if config.get('schemaVersion') != 1 or config.get('packageName') != play.PACKAGE or config.get('extensionId') != 'dbokmlpefliilbjldladbimlcfgbolhk':
        raise ValueError('Unexpected production store identity')
    locales = config['locales']
    if not 1 <= len(locales) <= 100 or 'en' not in locales:
        raise ValueError('Expected bounded store locale mappings and English')
    for field in ['play', 'chrome']:
        values = [row[field] for row in locales.values() if field in row]
        if len(values) != len(set(values)):
            raise ValueError('Duplicate store locale mapping')
    for locale, row in locales.items():
        if not re.fullmatch(r'[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*', locale):
            raise ValueError('Invalid canonical locale')
        if set(row) - {'play', 'chrome'} or 'play' not in row:
            raise ValueError('Invalid store locale fields')
        if not re.fullmatch(r'[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*', row['play']):
            raise ValueError('Invalid Play language')
        if 'chrome' in row and not re.fullmatch(r'[a-z]{2,3}(?:_[A-Z]{2})?', row['chrome']):
            raise ValueError('Invalid Chrome locale directory')
    registry = read(root / 'localization/locales.json')
    if {locale for locale, row in locales.items() if 'chrome' in row} != set(registry['supportedLocales']['web']):
        raise ValueError('Chrome locale mappings must match shipping React locales')
    return config


def catalog(platform, locale, root=ROOT, reviewed=True):
    paths = localization.CATALOGS[platform]
    source = read(root / paths[0])
    if locale == 'en':
        # Reuse exactly the importer constraints for English too.
        validator = localization.Workspace(root, platform, 'de')
        validator.validate_values(source)
        return source
    workspace = localization.Workspace(root, platform, locale)
    workspace.validate_values(workspace.translated)
    if reviewed and any(workspace.report().values()):
        raise ValueError(f'{platform}/{locale}: missing, stale or unreviewed resources: {workspace.report()}')
    if set(workspace.translated) != set(source):
        raise ValueError(f'{platform}/{locale}: incomplete catalog')
    return workspace.translated


def desired_play(root=ROOT):
    result = {}
    for locale, row in configuration(root)['locales'].items():
        values = catalog('store', locale, root)
        result[row['play']] = {field: values[key] for key, field in FIELDS.items()}
    return result


def generated(root=ROOT):
    english = catalog('extension', 'en', root)
    yield root / 'clients/extension/src/messages-en.js', '// Generated by scripts/store-listings.py generate.\nexport const english = ' + json.dumps(english, ensure_ascii=False, indent=2) + ';\n'
    for locale, row in configuration(root)['locales'].items():
        if 'chrome' not in row:
            continue
        values = catalog('extension', locale, root)
        # Chrome reserves $ for native substitutions; named DOM slots use braces.
        messages = {key: {'message': text.replace('$', '$$')} for key, text in values.items()}
        messages['catalog_locale'] = {'message': locale}
        messages['catalog_direction'] = {'message': 'ltr'}
        yield root / 'clients/extension/_locales' / row['chrome'] / 'messages.json', localization.json_text(messages)


def generate(root=ROOT, check=False):
    expected = {}
    for path, content in generated(root):
        expected[path] = content
        if check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise ValueError(f'Generated Chrome catalog is stale: {path.relative_to(root)}')
        else:
            localization.atomic_write(path, content)
    actual = set((root / 'clients/extension/_locales').glob('*/messages.json'))
    if actual - set(expected):
        raise ValueError('Unexpected generated Chrome locale; remove it explicitly')
    return len(expected) - 1


def chrome_text(root=ROOT):
    locales = {}
    for locale, row in configuration(root)['locales'].items():
        if 'chrome' not in row:
            continue
        locales[row['chrome']] = {'name': 'JSTorrent',
                                 'shortDescription': catalog('extension', locale, root)['extension_summary'],
                                 'description': catalog('store', locale, root)['chrome_full']}
    return {'schemaVersion': 1, 'extensionId': configuration(root)['extensionId'],
            'catalogHash': digest(locales), 'locales': locales}


def remote_listings(transaction):
    rows = transaction.get('/listings').get('listings', [])
    if not isinstance(rows, list) or len(rows) > 100:
        raise ValueError('Unexpected Play listing response')
    result = {}
    for row in rows:
        language = row['language']
        if language in result or not re.fullmatch(r'[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*', language):
            raise ValueError('Duplicate or invalid remote language')
        if set(row) - {'language', 'title', 'shortDescription', 'fullDescription', 'video'}:
            raise ValueError('Unknown Play listing field; inspect before changing metadata')
        result[language] = row
    return result


def plan_changes(current, desired):
    changes = []
    for language, fields in sorted(desired.items()):
        old = current.get(language, {})
        difference = {key: {'before': old.get(key), 'after': value} for key, value in fields.items() if old.get(key) != value}
        if difference:
            changes.append({'language': language, 'fields': difference})
    return {'schemaVersion': 1, 'packageName': play.PACKAGE, 'remoteHash': digest(current),
            'catalogHash': digest(desired), 'changes': changes}


def export_listings(google):
    with play.edit(google) as transaction:
        current = remote_listings(transaction)
    return {'schemaVersion': 1, 'packageName': play.PACKAGE,
            'exportedAt': datetime.now(timezone.utc).isoformat(), 'listings': current}


def diff_listings(google, desired):
    with play.edit(google) as transaction:
        return plan_changes(remote_listings(transaction), desired)


def apply_listings(google, desired, approved):
    if approved.get('schemaVersion') != 1 or approved.get('packageName') != play.PACKAGE:
        raise ValueError('Invalid reviewed listing plan')
    if approved.get('catalogHash') != digest(desired):
        raise ValueError('Catalogs changed after the listing diff')
    with play.edit(google) as transaction:
        current = remote_listings(transaction)
        actual = plan_changes(current, desired)
        if actual != approved:
            raise ValueError('Play changed since the reviewed diff; export and inspect a fresh plan')
        if not actual['changes']:
            return {'status': 'unchanged', 'packageName': play.PACKAGE, 'catalogHash': digest(desired)}
        for change in actual['changes']:
            language = change['language']
            fields = desired[language]
            # PATCH preserves unowned fields such as the promotional video.
            # Creating a new language requires the full three-field resource.
            method = 'PATCH' if language in current else 'PUT'
            path = f'{play.PUBLISHER}{transaction.path}/listings/{quote(language, safe="")}'
            google.call(method, path, fields)
        saved = remote_listings(transaction)
        expected = {language: {**row} for language, row in current.items()}
        for language, fields in desired.items():
            expected[language] = {**expected.get(language, {'language': language}), **fields}
        if saved != expected:
            raise ValueError('Play readback differs or unowned listing data changed')
        transaction.commit()
        return {'status': 'submitted', 'packageName': play.PACKAGE, 'catalogHash': digest(desired),
                'planHash': digest(approved), 'editId': transaction.id,
                'languages': [row['language'] for row in actual['changes']],
                'availability': 'API acceptance; Google review and public availability are separate'}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['check', 'generate', 'chrome-text', 'export', 'diff', 'apply'])
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--out', type=Path)
    parser.add_argument('--plan', type=Path)
    args = parser.parse_args(argv)
    try:
        if args.command == 'generate':
            print(f'Generated {generate(args.root)} Chrome locale catalogs')
            return 0
        if args.command == 'check':
            desired = desired_play(args.root)
            count = generate(args.root, check=True)
            print(f'{len(desired)} reviewed Play listings and {count} Chrome locale catalogs pass')
            return 0
        if args.command == 'chrome-text':
            if not args.out:
                raise ValueError('chrome-text requires --out')
            write(args.out, chrome_text(args.root))
            print(f'Prepared reviewed Chrome dashboard text: {args.out}')
            return 0
        if not args.out:
            raise ValueError('--out is required for remote operations')
        google = play.Http(os.environ.get('PLAY_ACCESS_TOKEN'))
        if args.command == 'export':
            result = export_listings(google)
        elif args.command == 'diff':
            result = diff_listings(google, desired_play(args.root))
        else:
            if not args.plan:
                raise ValueError('apply requires the exact reviewed --plan')
            result = apply_listings(google, desired_play(args.root), read(args.plan))
        write(args.out, result)
        print(json.dumps({'command': args.command, 'output': str(args.out),
                          'changes': len(result.get('changes', [])), 'status': result.get('status')}))
        return 0
    except (ValueError, RuntimeError, OSError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
