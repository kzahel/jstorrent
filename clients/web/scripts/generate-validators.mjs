function standalone(contract, validators, { useDefaults }) {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    validateFormats: false,
    // A host built before a field existed omits it. Rust's serde defaults are
    // in the schema, so validation fills them in and the TypeScript types,
    // which mark those fields present, stay true for older hosts.
    useDefaults,
    // Strict schema problems are reported through the logger so ignored
    // defaults can be checked against IGNORED_DEFAULTS; every other strict
    // schema warning still fails generation.
    strictSchema: "log",
    logger: {
      log() {},
      warn(message) {
        const ignored = /^strict mode: default is ignored for: (\S+)$/.exec(message);
        if (ignored !== null && IGNORED_DEFAULTS.has(ignored[1])) return;
        throw new Error(message);
      },
      error(message) {
        throw new Error(message);
      },
    },
    // Share larger referenced definitions across the exported entry points.
    inlineRefs: 3,
    code: {
      esm: true,
      optimize: true,
      source: true,
    },
  });
  ajv.addSchema(contract, schemaId);
  const references = Object.fromEntries(
    Object.entries(validators).map(([exportName, definition]) => [
      exportName,
      `${schemaId}#/$defs/${definition}`,
    ]),
  );
  for (const [exportName, reference] of Object.entries(references)) {
    if (ajv.getSchema(reference) === undefined) {
      throw new Error(`${exportName} references missing schema ${reference}`);
    }
  }
  const code = standaloneCode(ajv, references).replace(
    /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
    "const $1 = (value) => Array.from(value).length;",
  );
  if (/\brequire\s*\(/.test(code)) {
    throw new Error(
      "AJV generated a CommonJS runtime dependency for the browser validator",
    );
  }
  return code;
}

function declare(validators) {
  return Object.keys(validators)
    .map((exportName) => `export const ${exportName}: StandaloneValidateFunction;`)
    .join("\n");
}

/**
 * A host older than a property omits it. Unless the schema gives a default
 * (filled in during validation) or every released host's schema already has
 * the property, the TypeScript declaration must make it optional; otherwise
 * code typed against the newest contract reads `undefined` from an older host.
 */
function checkAbsentFieldsAreTyped(contract, declarations, released) {
  const problems = [];
  for (const [name, definition] of Object.entries(contract.$defs)) {
    // Declarations with documented fields span several lines; one ends where
    // the next top-level export begins.
    const declaration = new RegExp(
      `^export type ${name} = ([\\s\\S]*?)(?=^export |(?![\\s\\S]))`,
      "m",
    ).exec(declarations)?.[1];
    for (const [property, field, branch] of absentWithoutDefault(definition)) {
      if (released.every((schema) => hasProperty(schema.$defs[name], branch, property))) {
        continue;
      }
      if (declaration === undefined) {
        problems.push(`${name}.${property}: no TypeScript declaration`);
      } else if (
        new RegExp(`\\b${property}: `).test(declaration) &&
        !new RegExp(`\\b${property}\\?: `).test(declaration)
      ) {
        problems.push(`${name}.${property}: ${JSON.stringify(field).slice(0, 80)}`);
      }
    }
  }
  if (problems.length > 0) {
    throw new Error(
      "Fields a host may omit are typed as always present:\n" +
        problems.join("\n"),
    );
  }
}

function* absentWithoutDefault(definition, branch = null) {
  const required = new Set(definition.required ?? []);
  for (const [property, field] of Object.entries(definition.properties ?? {})) {
    if (required.has(property) || "default" in field) continue;
    yield [property, field, branch];
  }
  for (const key of ["oneOf", "anyOf"]) {
    for (const child of definition[key] ?? []) {
      yield* absentWithoutDefault(child, discriminator(child) ?? branch);
    }
  }
}

/** The tag that identifies a union branch, such as `field=value`. */
function discriminator(branch) {
  for (const [key, property] of Object.entries(branch.properties ?? {})) {
    if (property.const !== undefined) return `${key}=${String(property.const)}`;
  }
  return null;
}

/**
 * Whether a released host always sends the property when it sends its object:
 * the property exists there, or that host never sends the definition or
 * branch at all (so only newer hosts, which have the property, send it).
 */
function hasProperty(definition, branch, property) {
  if (definition === undefined) return true;
  const children = [...(definition.oneOf ?? []), ...(definition.anyOf ?? [])];
  if (branch === null) {
    return (
      definition.properties?.[property] !== undefined ||
      children.some((child) => child.properties?.[property] !== undefined)
    );
  }
  const matching = children.filter((child) => discriminator(child) === branch);
  return matching.length === 0 || matching.some((child) => child.properties?.[property] !== undefined);
}

/**
 * Accept what a newer host may add (docs/topics/mixed-version-compatibility.md):
 * object fields this client does not know, and row field updates of kinds it
 * does not know, which validation.ts then drops. Hosts still reject unknown
 * input; only these client validators are relaxed. New enum values and other
 * new variants stay strict and need a capability or the release order.
 */
function tolerateNewerHosts(contract) {
  const rowFieldKinds = {};
  for (const [name, definition] of Object.entries(contract.$defs)) {
    const kinds = fieldDiscriminators(definition.oneOf);
    if (kinds === null) continue;
    rowFieldKinds[name] = kinds;
    definition.oneOf.push({
      type: "object",
      properties: { field: { type: "string", not: { enum: kinds } } },
      required: ["field"],
    });
  }
  openObjects(contract);
  return rowFieldKinds;
}

function fieldDiscriminators(branches) {
  if (!Array.isArray(branches) || branches.length === 0) return null;
  const kinds = branches.map((branch) => branch.properties?.field?.const);
  return kinds.every((kind) => typeof kind === "string") ? kinds : null;
}

function openObjects(value) {
  if (Array.isArray(value)) {
    value.forEach(openObjects);
  } else if (value !== null && typeof value === "object") {
    if (value.additionalProperties === false) delete value.additionalProperties;
    Object.values(value).forEach(openObjects);
  }
}
