#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { platformLocales, readLocaleRegistry } from "../../../scripts/localization-registry.mjs";

const scriptPath = fileURLToPath(import.meta.url);
const repositoryRoot = path.resolve(path.dirname(scriptPath), "../../..");
const require = createRequire(import.meta.url);

/** Only registered catalogs become imports; stale generated JSON stays inert. */
export function renderCatalogModule(registry) {
  const locales = platformLocales(registry, "web", true);
  const supported = platformLocales(registry, "web");
  const preview = locales.filter((locale) => !supported.includes(locale));
  const identifier = (locale) => `catalog${locales.indexOf(locale)}`;
  const imports = locales.map((locale) => `import ${identifier(locale)} from ${JSON.stringify(`./${locale}.json`)};`);
  const entries = (tags) => tags.map((locale) => `  ${JSON.stringify(locale)}: ${identifier(locale)},`).join("\n");
  const metadata = {
    sourceLocale: registry.sourceLocale,
    fallbackLocale: registry.fallbackLocale,
    supportedLocales: supported,
    previewLocales: preview,
    localeDefinitions: Object.fromEntries(locales.map((locale) => [locale, registry.localeDefinitions[locale]])),
    testLocales: registry.testLocales,
  };
  return `// Generated by scripts/generate-localization.mjs. Do not edit.\n${imports.join("\n")}\n\nexport const localeRegistry = ${JSON.stringify(metadata, null, 2)} as const;\n\nexport const sourceCatalog = ${identifier(registry.sourceLocale)};\nconst supportedCatalogs = {\n${entries(supported)}\n};\nconst previewCatalogs = import.meta.env.VITE_RSTORRENT_ENABLE_PREVIEW_LOCALES === "1" ? {\n${entries(preview)}\n} : {};\nexport const catalogs = { ...supportedCatalogs, ...previewCatalogs };\n`;
}

export function generateLocalization(root = repositoryRoot, compiler = require.resolve("@formatjs/cli/bin/formatjs")) {
  const registry = readLocaleRegistry(root);
  const sourceDirectory = path.dirname(path.resolve(root, registry.catalogs.web));
  const outputDirectory = path.join(root, "clients/web/src/localization/generated");
  fs.mkdirSync(outputDirectory, { recursive: true });
  for (const locale of platformLocales(registry, "web", true)) {
    const source = path.join(sourceDirectory, `${locale}.json`);
    if (!fs.existsSync(source)) throw new Error(`Registered web catalog is missing: ${source}`);
    // npm's .bin shim is platform-specific; run the JavaScript CLI with Node.
    execFileSync(process.execPath, [compiler, "compile", source, "--ast", "--out-file", path.join(outputDirectory, `${locale}.json`)], { stdio: "inherit" });
  }
  const output = path.join(outputDirectory, "catalogs.ts");
  const generated = renderCatalogModule(registry);
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== generated) fs.writeFileSync(output, generated);
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === scriptPath) generateLocalization();
